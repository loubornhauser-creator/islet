import AppKit

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date

    /// Eine Zeile für die Liste.
    var preview: String {
        let line = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
        let t = line.trimmingCharacters(in: .whitespaces)
        return t.count > 90 ? String(t.prefix(90)) + "…" : t
    }
}

/// Zwischenablage-Verlauf. Nur im Arbeitsspeicher (nichts wird auf die Platte geschrieben),
/// Passwort-Manager und als „vertraulich“ markierte Einträge werden ignoriert.
final class Clipboard: ObservableObject {
    static let shared = Clipboard()

    @Published var items: [ClipItem] = []
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.1password.1password", "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type",
    ]

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 1.0, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.4
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate(); timer = nil
        items.removeAll()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let s = pb.string(forType: .string),
              !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              s.count < 20_000 else { return }
        items.removeAll { $0.text == s }
        items.insert(ClipItem(text: s, date: Date()), at: 0)
        let max = Swift.max(3, Pref.int("clipboardMax"))
        if items.count > max { items.removeLast(items.count - max) }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastCount = pb.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(ClipItem(text: item.text, date: Date()), at: 0)
    }

    func clear() { items.removeAll() }
}
